import { defineConfig } from 'vite';

/**
 * Build config tuned for two targets:
 *   • Cloudflare Pages  — static `dist/`, long-immutable asset hashing
 *   • Electron desktop  — relative base so the packaged build works from file://
 *                         and from the tiny local server the shell spins up
 */
export default defineConfig({
  base: './',
  server: {
    host: '0.0.0.0',
    port: 5173,
    strictPort: false,
    // The e2b preview proxy and the Electron shell both use non-localhost hosts.
    allowedHosts: true,
    cors: true,
    hmr: { clientPort: 443, protocol: 'wss' },
  },
  preview: { host: '0.0.0.0', port: 4173, allowedHosts: true, cors: true },
  build: {
    target: 'es2022',
    outDir: 'dist',
    assetsDir: 'assets/_',
    sourcemap: false,
    chunkSizeWarningLimit: 1800,
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (id.includes('node_modules/three')) return 'three';
          return undefined;
        },
        assetFileNames: 'assets/_/[name]-[hash][extname]',
      },
    },
  },
  // public/assets is generated by `npm run assets`; keep the dev server calm about it.
  assetsInclude: ['**/*.glb', '**/*.ogg', '**/*.mp3'],
});
