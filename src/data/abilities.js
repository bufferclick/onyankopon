/** Rank scaling: returns multipliers for a given rank (1-based). */
export function rankScale(ability, rank = 1) {
  const r = Math.max(1, Math.min(ability.maxRank || 1, rank));
  const step = r - 1;
  const rankDef = ability.rank || {};
  return {
    damage: 1 + (rankDef.damage || 0) * step,
    cooldown: Math.max(1.2, (ability.cooldown || 6) + (rankDef.cooldown || 0) * step),
    radius: 1 + (rankDef.radius || 0) * step,
    duration: (ability.duration || 0) + (rankDef.duration || 0) * step,
    rank: r,
  };
}
